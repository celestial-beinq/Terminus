// Terminus Environment Synchronizer & Security Gatekeeper
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');
const envPath = path.join(rootDir, '.env');

// Simple .env parser to avoid runtime dependencies
function loadEnvFile(filePath) {
  if (!fs.existsSync(filePath)) return {};
  const content = fs.readFileSync(filePath, 'utf-8');
  const env = {};
  for (const line of content.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eqIdx = trimmed.indexOf('=');
    if (eqIdx !== -1) {
      const key = trimmed.slice(0, eqIdx).trim();
      let val = trimmed.slice(eqIdx + 1).trim();
      if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
        val = val.slice(1, -1);
      }
      env[key] = val;
    }
  }
  return env;
}

const fileEnv = loadEnvFile(envPath);
const getVar = (key, fallback = '') => process.env[key] || fileEnv[key] || fallback;

// 1. Validate Supabase URL
const supabaseUrl = getVar('SUPABASE_URL').trim();
if (!supabaseUrl) {
  console.warn('[SECURITY WARNING] SUPABASE_URL is missing.');
} else if (!supabaseUrl.startsWith('https://')) {
  throw new Error(`[SECURITY ERROR] SUPABASE_URL must start with https://. Found: ${supabaseUrl}`);
}

// 2. Validate Supabase Anon Key & verify it is NOT a service_role key
const supabaseAnonKey = getVar('SUPABASE_ANON_KEY').trim();
if (!supabaseAnonKey) {
  console.warn('[SECURITY WARNING] SUPABASE_ANON_KEY is missing.');
} else {
  const parts = supabaseAnonKey.split('.');
  if (parts.length === 3) {
    try {
      const payloadJson = Buffer.from(parts[1], 'base64').toString('utf-8');
      const payload = JSON.parse(payloadJson);
      if (payload.role && payload.role !== 'anon') {
        throw new Error(`[CRITICAL SECURITY ALERT] SUPABASE_ANON_KEY has role "${payload.role}". Only "anon" keys can be placed in client environments!`);
      }
    } catch (e) {
      if (e.message.includes('CRITICAL SECURITY ALERT')) throw e;
      // If parsing fails for non-standard JWT, continue with caution
    }
  }
}

// 3. Ensure no service_role key or backend secret is leaked into frontend environment
const forbiddenKeywords = ['SERVICE_ROLE', 'SECRET_KEY', 'PRIVATE_KEY'];
for (const key of Object.keys({ ...process.env, ...fileEnv })) {
  if (forbiddenKeywords.some((w) => key.toUpperCase().includes(w))) {
    console.log(`[SECURITY AUDIT] Detected server secret: ${key}. Ensuring it is NEVER leaked to client environment.`);
  }
}

const isDebug = getVar('DEBUG', 'false').toLowerCase() === 'true';

const envDir = path.join(rootDir, 'src', 'environments');
fs.mkdirSync(envDir, { recursive: true });

function createEnvFile(isProduction, debug) {
  return `// Auto-generated by scripts/set-env.mjs — DO NOT EDIT DIRECTLY
export const environment = {
  production: ${isProduction},
  debug: ${debug},
  supabaseUrl: ${JSON.stringify(supabaseUrl)},
  supabaseAnonKey: ${JSON.stringify(supabaseAnonKey)},
};
`;
}

fs.writeFileSync(path.join(envDir, 'environment.ts'), createEnvFile(true, false), 'utf-8');
fs.writeFileSync(path.join(envDir, 'environment.development.ts'), createEnvFile(false, isDebug), 'utf-8');

console.log(`[set-env] Successfully generated src/environments/environment.ts (production: true, debug: false)`);
console.log(`[set-env] Successfully generated src/environments/environment.development.ts (production: false, debug: ${isDebug})`);
